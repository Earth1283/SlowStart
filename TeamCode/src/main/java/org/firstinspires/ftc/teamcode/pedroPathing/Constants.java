package org.firstinspires.ftc.teamcode.pedroPathing;

import com.pedropathing.follower.Follower;
import com.pedropathing.follower.FollowerConstants;
import com.pedropathing.ftc.FollowerBuilder;
import com.pedropathing.ftc.drivetrains.MecanumConstants;
import com.pedropathing.ftc.localization.constants.PinpointConstants;
import com.pedropathing.paths.PathConstraints;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;

/**
 * Pedro Pathing configuration for FTC team 32008 (DECODE 2025-26).
 *
 * Generated by the refract FTC suite (ftc-construct) against the team's confirmed
 * team-config.yaml. See _meta.suite_generated_code in that file.
 *
 * Grounded in library-docs/pedro-pathing/{installation,localization-tuning,examples}.md
 * (fetched 2026-07-12). Every builder call below appears verbatim in those docs;
 * nothing here is recalled from memory.
 */
public class Constants {

    public static FollowerConstants followerConstants = new FollowerConstants()
            // Robot mass in KILOGRAMS, with battery installed. Supplied by team: 12.55.
            .mass(12.55);

    // ---------------------------------------------------------------------
    // NOT YET TUNED -- deliberately omitted so Pedro's own library defaults
    // apply, rather than shipping invented numbers. Add each line back once
    // you have run the tuner that produces it. Until then the robot WILL
    // follow paths sloppily; it will not follow them wrongly.
    //
    //   .forwardZeroPowerAcceleration(...)   <- Forward Zero Power Accel tuner
    //   .lateralZeroPowerAcceleration(...)   <- Lateral Zero Power Accel tuner
    //   .translationalPIDFCoefficients(...)  <- Translational PIDF tuner
    //   .headingPIDFCoefficients(...)        <- Heading PIDF tuner
    //   .drivePIDFCoefficients(...)          <- Drive PIDF tuner
    //   .centripetalScaling(...)             <- Centripetal tuner
    //
    // See library-docs/pedro-pathing/pidf-tuning.md and tuning.md for the order
    // to run them in. Full worked example: examples.md "Example Constants".
    // ---------------------------------------------------------------------

    public static MecanumConstants driveConstants = new MecanumConstants()
            .leftFrontMotorName("lf")
            .leftRearMotorName("lb")
            .rightFrontMotorName("rf")
            .rightRearMotorName("rb")
            // Team chose the standard mecanum wiring: both left motors reversed.
            // Verify on-robot with the Tuning OpMode > Localization > Motor Directions test
            // before trusting an auto run (troubleshooting.md: wrong motor association is
            // the usual cause of "robot turns 180 and oscillates").
            .leftFrontMotorDirection(DcMotorSimple.Direction.REVERSE)
            .leftRearMotorDirection(DcMotorSimple.Direction.REVERSE)
            .rightFrontMotorDirection(DcMotorSimple.Direction.FORWARD)
            .rightRearMotorDirection(DcMotorSimple.Direction.FORWARD);
    // TODO(32008): add .xVelocity(...) from ForwardVelocityTest and
    //              .yVelocity(...) from StrafeVelocityTest once measured (tuning.md).

    public static PinpointConstants localizerConstants = new PinpointConstants()
            // Team measured 13.5 cm, forward pod RIGHT of the center of rotation.
            // Pedro's frame is +X forward / +Y left, so right-of-center is negative.
            // 13.5 cm / 2.54 = 5.3150 in.
            .forwardPodY(-5.3150)
            // Team reported the strafe pod level with the center of rotation (its 12.5 cm
            // is a purely sideways offset, which Pedro does not use for this pod).
            .strafePodX(0.0)
            .distanceUnit(DistanceUnit.INCH)
            // Pinpoint device name in the robot configuration. Confirmed on an I2C
            // port other than 0 (port 0 is taken by the Control Hub's internal IMU).
            .hardwareMapName("pp")
            .encoderResolution(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD)
            // Directions left at default. Verify with Tuning OpMode > Localization Test:
            // push the robot FORWARD, x must increase; push it LEFT, y must increase.
            // If either goes the wrong way, flip that encoder here.
            .forwardEncoderDirection(GoBildaPinpointDriver.EncoderDirection.FORWARD)
            .strafeEncoderDirection(GoBildaPinpointDriver.EncoderDirection.FORWARD);

    // tValueConstraint, velocityConstraint, translationalConstraint, headingConstraint
    // -- the starting values from the Pedro constants docs page.
    public static PathConstraints pathConstraints = new PathConstraints(0.99, 100, 1, 1);

    public static Follower createFollower(HardwareMap hardwareMap) {
        return new FollowerBuilder(followerConstants, hardwareMap)
                .mecanumDrivetrain(driveConstants)
                .pinpointLocalizer(localizerConstants)
                .pathConstraints(pathConstraints)
                .build();
    }
}
