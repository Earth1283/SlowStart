    public static FollowerConstants followerConstants = new FollowerConstants()
            .mass(12.55)
            .forwardZeroPowerAcceleration(-23.69353949060179)
            .lateralZeroPowerAcceleration(-59.22595640999532)
            // Predictive braking, from the team's brake profile tuner.
            //
            // ARGUMENT ORDER IS (P, kLinearBraking, kQuadraticFriction) -- verified by
            // decompiling PredictiveBrakingCoefficients in core-2.1.2. The constructor
            // forwards to setCoefficients(P, kLinear, kQuadratic, maxPower), so passing
            // the two tuned values in the order they are usually quoted (linear first,
            // then quadratic) would silently land them in P and kLinearBraking. It would
            // compile and brake wrongly. Keep P first.
            //
            // P = 0.15 is Pedro's own default -- the team supplied kLinear and kQuadratic
            // only. Pedro's defaults for all three are (0.15, 0.1, 0.001), so both tuned
            // values sit close to stock, which is a good sign the tuner behaved.
            //
            // maximumBrakingPower defaults to 0.2. Add .withMaximumBrakingPower(x) on the
            // coefficients object to change it; it clamps to [0.0001, 1.0].
            //
            // This call also flips usePredictiveBraking to true on its own (it defaults
            // to false) -- there is no separate enable flag to set.
            .predictiveBrakingCoefficients(new PredictiveBrakingCoefficients(
                    0.15,                   // P
                    0.09175869900913709,    // kLinearBraking
                    0.001674576037470166    // kQuadraticFriction
            ))

            // Translational PIDF -- TUNED ON THIS ROBOT via the Translational Tuner.
            // PIDFCoefficients order is (P, I, D, F).
            .translationalPIDFCoefficients(new PIDFCoefficients(
                    0.11,   // P
                    0.0,    // I
                    0.025,  // D
                    0.0     // F
            ))

            // Heading PIDF -- NOT YET CONVERGED. Starting point, expect to iterate.
            //
            // Running 19859's gains (P 2.4935, D 0.2301) made this robot wobble badly on
            // return. That is classic too-much-P: 32008 is 12.55 kg against 19859's 14.45,
            // so less rotational inertia, so the same P overshoots and rings.
            //
            // P cut ~40% and D raised ~40% to damp the ring. ON THE NEXT RUN:
            //   still wobbling      -> drop P another 20% (1.5 -> 1.2), leave D
            //   slow / stops short  -> raise P back toward 1.9
            //   sharp but jittery   -> lower D toward 0.25
            // The twist-to-the-right seen during straight-line driving is THIS loop, not
            // the drive PIDF -- retest drive only after heading holds angle.
            .headingPIDFCoefficients(new PIDFCoefficients(
                    1.5,    // P   (was 2.4935 from 19859)
                    0.0,    // I
                    0.32,   // D   (was 0.2301 from 19859)
                    0.0     // F
            ))

            // Drive PIDF -- 19859's values, UNVERIFIED on this robot, kept at the team's
            // instruction. FilteredPIDFCoefficients order is (P, I, D, T, F): T is a
            // filter time constant in slot 4, F is slot 5. The field DECLARATION order in
            // that class is P,I,D,F,T -- different from the constructor. Do not reorder
            // these by reading the field list.
            .drivePIDFCoefficients(new FilteredPIDFCoefficients(
                    0.013,  // P
                    0.0,    // I
                    0.0005, // D
                    0.6,    // T -- filter, not a gain
                    0.0     // F
            ))

            // Centripetal scaling of 0 DISABLES centripetal correction entirely (Pedro's
            // own default is 0.0005). With it off, the robot drifts wide on every curve --
            // which matches the "occasional curves" drift reported during straight-line
            // testing. Set as instructed, but this is the one value here that is off
            // rather than tuned. Run the Centripetal Tuner once heading is settled.
            .centripetalScaling(0);

    public static MecanumConstants driveConstants = new MecanumConstants()
            .leftFrontMotorName(robotConfigs.LEFT_FRONT)
            .leftRearMotorName(robotConfigs.LEFT_BACK)
            .rightFrontMotorName(robotConfigs.RIGHT_FRONT)
            .rightRearMotorName(robotConfigs.RIGHT_BACK)
            .leftFrontMotorDirection(DcMotorSimple.Direction.REVERSE)
            .leftRearMotorDirection(DcMotorSimple.Direction.REVERSE)
            .rightFrontMotorDirection(DcMotorSimple.Direction.FORWARD)
            .rightRearMotorDirection(DcMotorSimple.Direction.FORWARD)
            // Forward / Lateral Velocity Tuners. Strafe is 78.5% of forward (a 21.5%
            // loss to mecanum roller slip), which is the expected 20-30% band -- an
            // earlier pair had lateral FASTER than forward, which is physically
            // impossible and meant the encoder directions were still wrong.
            .xVelocity(80.85435906357654)
            .yVelocity(63.44764192836492)
            // Scales motor output by nominalVoltage / measuredVoltage every loop, so path
            // following behaves the same on a tired pack as on a fresh one. Without it the
            // robot follows correctly at 13.5 V and undershoots at 11.5 V -- the classic
            // "worked all practice, missed in match 5" failure. 19859 runs this too.
            // There is also .nominalVoltage(double) if the default reference needs changing.
            .useVoltageCompensation(true)
            .maxPower(1);

    public static PinpointConstants localizerConstants = new PinpointConstants()
            .forwardPodY(-5.3150)
            .strafePodX(0.0)
            .distanceUnit(DistanceUnit.INCH)
            .hardwareMapName(robotConfigs.PIN_POINT)
            .encoderResolution(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD)
            .forwardEncoderDirection(GoBildaPinpointDriver.EncoderDirection.FORWARD)
            .strafeEncoderDirection(GoBildaPinpointDriver.EncoderDirection.REVERSED);

    // Expanded from the 4-argument form to the 8-argument one ONLY to reach
    // brakingStrength. The 4-arg constructor forwards to this exact 8-arg call with
    // velocity=0.1, translational=0.1, heading=0.007, searchLimit=10 -- verified by
    // decompiling PathConstraints in core-2.1.2 -- so every value below except
    // brakingStrength is byte-for-byte what the old 4-arg line already produced.
    //
    // brakingStrength lowered 1.0 -> 0.8 to soften the stop. The robot rotates slightly
    // LEFT every time it brakes; Pedro's own troubleshooting page names brakingStrength
    // as the lever for rough braking. Softer deceleration gives the heading loop time to
    // hold angle through the transient instead of being outrun by it.
    //
    // IF THE LEFT KICK SURVIVES THIS, it is not a braking-strength problem:
    //   - a CONSISTENT one-direction kick points at asymmetry, not tuning -- check for a
    //     dragging wheel, uneven compression, or one motor with a weaker brake
    //   - or the heading P (1.5) is too low to correct during deceleration; it was cut
    //     from 19859's 2.4935 to stop a wobble, and may now be under-damped the other way
    public static PathConstraints pathConstraints = new PathConstraints(
            0.99,   // tValueConstraint
            0.1,    // velocityConstraint      (4-arg default)
            0.1,    // translationalConstraint (4-arg default)
            0.007,  // headingConstraint       (4-arg default)
            100,    // timeoutConstraint
            0.8,    // brakingStrength         (was 1)
            10,     // BEZIER_CURVE_SEARCH_LIMIT (4-arg default, leave at 10)
            1       // brakingStart
    );

    public static Follower createFollower(HardwareMap hardwareMap) {
        return new FollowerBuilder(followerConstants, hardwareMap)
                .mecanumDrivetrain(driveConstants)
                .pinpointLocalizer(localizerConstants)
                .pathConstraints(pathConstraints)
                .build();
    }
